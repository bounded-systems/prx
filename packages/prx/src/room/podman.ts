/**
 * Podman driver (prx-asr) — render a {@link PodSpec} to a Kubernetes Pod
 * manifest for `podman kube play`, mirroring the executor's Lima driver
 * (`executor/lima.ts` → `renderLima`): plain text built field-by-field for our
 * known schema (no YAML dependency, readable result), validated at the seam.
 *
 * The mapping:
 *   - each NON-SECRET room → a container (sharing the pod's namespaces, the
 *     podman-pod property that makes the door sockets reachable across rooms).
 *     A secret-holding room (e.g. keeperd, prx-b44y) is NOT rendered here — it
 *     runs via `podman run --secret` ({@link renderPodmanRun}) since kube-play
 *     can't mount a host secret — but it STAYS in door resolution, so a consumer
 *     (claude-room) still gets its wired-door env and reaches it on the fabric;
 *   - the door fabric (`doorDir`) → one shared `hostPath` volume mounted into
 *     every container at the same path, so the unix-socket doors live on a host
 *     dir BOTH runtimes (kube pod + standalone secret containers) mount. On a
 *     linux host `/run` is tmpfs, so the sockets stay memory-backed;
 *   - each container's env → {@link podRoomEnv} for that room — the wired-door
 *     projection, i.e. `PRX_BEADS_DOOR`/`PRX_BEADS_SOCKET` for the beadsd
 *     consumer. A closed/unresolved door contributes no env (it isn't wired).
 *
 * The container *image* is the room's `RoomSpec.image` (its `-box`) when
 * declared, else a deterministic placeholder ref. The full registry ref is a
 * deploy concern (prx-zj8); everything else is real.
 */

import { PodSpecSchema, podRoomEnv, type PodSpec } from "./pod.ts";
import { roomNeedsSecretRuntime, roomSecrets } from "./spec.ts";

/** A YAML double-quoted scalar — JSON string syntax is a valid YAML 1.2 scalar. */
function dq(value: string): string {
  return JSON.stringify(value);
}

/** POSIX single-quote a string for safe interpolation into a `sh -c` command. */
function sq(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/**
 * Render the host argv that **provisions + relabels the shared door fabric**
 * before any room runs (prx-3urm). Pure — the thin runner wrapper lives in
 * `./podman-runtime.provisionDoorFabric`. Two live findings on an
 * SELinux-enforcing podman host (Fedora applehv VM) made this a required
 * pre-step:
 *
 *   1. `podman run --volume <doorDir>:<doorDir>:z` does NOT create a missing
 *      host source dir — it dies with `statfs … no such file or directory`. An
 *      all-secret-rooms pod has no `kube play` step (whose hostPath
 *      `DirectoryOrCreate` would create the dir), so it must be made here.
 *   2. The relabel must land BEFORE `kube play`: kube-play's `DirectoryOrCreate`
 *      makes the dir `var_run_t`, so the kube containers hit EACCES before the
 *      secret room's own `:z` ever runs. Relabeling here, first, fixes the order.
 *
 * `mkdir -p` then a best-effort `chcon -R -t container_file_t` (== the shared
 * `:z` label). The chcon is guarded — skipped when `chcon` is absent (a
 * non-SELinux host) and `|| true` if it fails (unprivileged) — so provisioning
 * stays correct off SELinux and only tightens the label where it matters; a
 * failed `mkdir`, by contrast, aborts (`set -e`) and fails the bring-up.
 */
export function renderDoorFabricProvision(doorDir: string): string[] {
  const dir = sq(doorDir);
  return [
    "sh",
    "-c",
    `set -e; mkdir -p ${dir}; ` +
      `command -v chcon >/dev/null 2>&1 && chcon -R -t container_file_t ${dir} || true`,
  ];
}

/** The shared door-fabric volume name. */
const DOOR_VOLUME = "prx-doors";
/** The repo bind-mount volume name + its in-container path (the daemon `WorkingDir`). */
const REPO_VOLUME = "prx-repo";
const WORK_DIR = "/work";

/**
 * A pod driver: render a {@link PodSpec} to its native orchestration config.
 * Mirrors `ExecutorDriver` — adding a driver must not touch the room/pod specs.
 */
export interface PodDriver {
  /** Stable driver id, e.g. `podman`. */
  readonly id: string;
  /** Render the spec to the driver's native config text. */
  render(pod: PodSpec): string;
}

/**
 * Render a {@link PodSpec} to a `podman kube play` Pod manifest. Validates the
 * spec at the seam (throws on a malformed pod) so a bad input never yields
 * half-config.
 */
export function renderPodmanKube(pod: PodSpec): string {
  const p = PodSpecSchema.parse(pod);
  const lines: string[] = [
    "# Generated by prx (pod spec → podman driver, prx-asr). Do not hand-edit.",
    "apiVersion: v1",
    "kind: Pod",
    "metadata:",
    `  name: ${dq(p.name)}`,
    "spec:",
    // The door fabric: the host doorDir, shared by every room's container AND by
    // the standalone secret-room containers (prx-b44y) — a hostPath both runtimes
    // mount, not a pod-private emptyDir. DirectoryOrCreate so podman provisions it.
    "  volumes:",
    `    - name: ${DOOR_VOLUME}`,
    "      hostPath:",
    `        path: ${dq(p.doorDir)}`,
    "        type: DirectoryOrCreate",
  ];

  // The repo bind-mount: the daemon images' WorkingDir is `/work` (the repo they
  // operate on); podman/crun won't start a container whose WorkingDir is missing,
  // so without this the daemon rooms fail (prx-u5lx). A hostPath of the pod's
  // repo, mounted at `/work` in every room below.
  if (p.repo) {
    lines.push(
      `    - name: ${REPO_VOLUME}`,
      "      hostPath:",
      `        path: ${dq(p.repo)}`,
      "        type: Directory",
    );
  }

  lines.push("  containers:");

  for (const room of p.rooms) {
    // A secret-holding room runs via `podman run --secret` (renderPodmanRun),
    // not as a kube container — but it remains in door resolution above, so its
    // consumers still get the wired-door env and reach it on the shared fabric.
    if (roomNeedsSecretRuntime(room)) continue;
    lines.push(`    - name: ${dq(room.name)}`);
    // The room's `-box` image when declared; else a deterministic placeholder
    // (a room with no image yet — the full registry ref is a prx-zj8 concern).
    if (room.image) {
      lines.push(`      image: ${dq(room.image)}`);
    } else {
      lines.push(
        `      image: ${dq(`prx/${room.name}:latest`)} # TODO(prx-zj8): no image declared`,
      );
    }
    lines.push("      volumeMounts:");
    lines.push(`        - name: ${DOOR_VOLUME}`);
    lines.push(`          mountPath: ${dq(p.doorDir)}`);
    if (p.repo) {
      lines.push(`        - name: ${REPO_VOLUME}`);
      lines.push(`          mountPath: ${dq(WORK_DIR)}`);
    }

    const env = podRoomEnv(p, room.name);
    const keys = Object.keys(env).sort();
    if (keys.length > 0) {
      lines.push("      env:");
      for (const key of keys) {
        lines.push(`        - name: ${key}`);
        lines.push(`          value: ${dq(env[key]!)}`);
      }
    }
  }

  return lines.join("\n") + "\n";
}

/**
 * Render the `podman run` argv (after the `podman` argv0) for a secret-holding
 * room — the runtime kube-play can't deliver (prx-b44y), since `podman kube
 * play` only accepts in-YAML k8s Secrets (base64-ing the key into the manifest,
 * which the door ADR forbids). The room runs as its own detached container that
 * mounts the SAME host door fabric the kube pod mounts, so its exposed door is
 * reachable cross-runtime; its host-backed secrets are injected via
 * `--secret <name>,target=<path>` (tmpfs, never a layer).
 *
 * Throws if `roomName` is not a member of `pod`, or if the named room holds no
 * secret (a non-secret room belongs in the kube pod — calling this on it is a
 * wiring error, not a silent no-op).
 */
export function renderPodmanRun(pod: PodSpec, roomName: string): string[] {
  const p = PodSpecSchema.parse(pod);
  const room = p.rooms.find((r) => r.name === roomName);
  if (!room) {
    throw new Error(`room '${roomName}' is not a member of pod '${p.name}'`);
  }
  if (!roomNeedsSecretRuntime(room)) {
    throw new Error(
      `room '${roomName}' holds no secret — it runs in the kube pod, not via 'podman run --secret'`,
    );
  }

  const args: string[] = [
    "run",
    "--detach",
    // Idempotent re-up: replace a same-named container from a prior play.
    "--replace",
    "--name",
    secretRoomContainer(p, room.name),
  ];
  // Host-backed secrets → tmpfs at the declared target (never a plaintext layer).
  for (const secret of roomSecrets(room)) {
    args.push("--secret", `${secret.name},target=${secret.target}`);
  }
  // The shared door fabric: the SAME host doorDir the kube pod hostPath-mounts,
  // so this standalone container's exposed door is reachable across runtimes.
  // `:z` = SHARED SELinux relabel (container_file_t, shared) — required on an
  // SELinux-enforcing host (e.g. a Fedora podman machine), else the keeper hits
  // EACCES creating its socket on the unlabeled (var_run_t) dir; SHARED (`:z`)
  // not private (`:Z`) because the dir is shared with the kube pod's containers.
  // A no-op on non-SELinux hosts. Live-validated on the host (prx-3urm).
  args.push("--volume", `${p.doorDir}:${p.doorDir}:z`);
  // The repo bind-mount + WorkingDir (mirrors the kube pod; prx-u5lx). `:z` for
  // the same SELinux reason — the repo is shared by every room.
  if (p.repo) {
    args.push("--volume", `${p.repo}:${WORK_DIR}:z`, "--workdir", WORK_DIR);
  }
  // Consumer env (doors this room consumes — usually empty for secret rooms).
  const env = podRoomEnv(p, room.name);
  for (const key of Object.keys(env).sort()) {
    args.push("--env", `${key}=${env[key]!}`);
  }
  // Server socket env: for each door this room EXPOSES, inject the env var that
  // tells the daemon where to create its socket on the shared fabric. Convention:
  // `${doorName.toUpperCase()}_SOCK` — matches door-kit's client convention so
  // the same var configures both ends. E.g. keeperd → KEEPERD_SOCK.
  for (const door of room.doors) {
    if (door.direction === "expose") {
      const socketFile = door.socket.split("/").at(-1) ?? door.socket;
      args.push("--env", `${door.name.toUpperCase()}_SOCK=${p.doorDir}/${socketFile}`);
    }
  }
  // The room's -box image; full registry ref resolved at deploy (prx-zj8).
  args.push(room.image ?? `prx/${room.name}:latest`);
  return args;
}

/** The container name for a secret room — stable, so `down` can target it. */
export function secretRoomContainer(pod: PodSpec, roomName: string): string {
  return `${pod.name}-${roomName}`;
}

/** The quadlet unit filename for a secret room (drop into `containers/systemd/`). */
export function quadletUnitName(pod: PodSpec, roomName: string): string {
  return `${secretRoomContainer(pod, roomName)}.container`;
}

/**
 * Render the **production** runtime form for a secret-holding room (prx-b44y): a
 * systemd podman **quadlet** (`.container`) unit. This is the durable counterpart
 * of {@link renderPodmanRun}'s ad-hoc argv — same wiring (the host-backed
 * `Secret=`, the shared door fabric, the repo `/work` mount, the wired-door env),
 * but managed by systemd (restart-on-failure, boot-time bring-up) the way
 * `~/claude-box`'s `quadlet/keeperd.container` + `nixos/doors.nix` already run the
 * door daemons.
 *
 * Borrowed from claude-box's door units: the **capability hardening floor**
 * (`NoNewPrivileges`, `DropCapability=all`, pid/memory caps). NOT borrowed:
 * claude-box pins keeperd to `Network=none` (its keeperd is socket-only) — prx's
 * keeperd HOLDS the push credential and must reach the git remote, so egress
 * stays at the podman default here. Confining that egress to a netd door (the
 * `scout-netd` pattern in doors.nix) is a later hardening step, noted in-unit.
 *
 * The signing key is delivered exactly as {@link renderPodmanRun} delivers it —
 * `Secret=<name>,target=<path>` from a host-created podman secret (`podman secret
 * create <name>`, sourced from the operator's store), landed on tmpfs, never a
 * layer or the manifest.
 *
 * Throws on the same wiring errors as {@link renderPodmanRun}: an unknown room,
 * or a non-secret room (which belongs in the kube pod, not its own unit).
 */
export function renderPodmanQuadlet(pod: PodSpec, roomName: string): string {
  const p = PodSpecSchema.parse(pod);
  const room = p.rooms.find((r) => r.name === roomName);
  if (!room) {
    throw new Error(`room '${roomName}' is not a member of pod '${p.name}'`);
  }
  if (!roomNeedsSecretRuntime(room)) {
    throw new Error(
      `room '${roomName}' holds no secret — it runs in the kube pod, not a podman quadlet`,
    );
  }

  const container = secretRoomContainer(p, room.name);
  const lines: string[] = [
    "# Generated by prx (pod spec → podman quadlet, prx-b44y). Do not hand-edit.",
    `# Install: cp ${quadletUnitName(p, room.name)} ~/.config/containers/systemd/`,
    "#          systemctl --user daemon-reload && systemctl --user start " + `${container}`,
    "[Unit]",
    `Description=prx ${container} — secret-holding door daemon (prx-b44y)`,
    "",
    "[Container]",
    `Image=${room.image ?? `prx/${room.name}:latest`}`,
    `ContainerName=${container}`,
  ];

  // Host-backed secrets → tmpfs at the declared target (never a layer/manifest).
  for (const secret of roomSecrets(room)) {
    lines.push(`Secret=${secret.name},target=${secret.target}`);
  }
  // The shared door fabric — the SAME host doorDir the kube pod hostPath-mounts,
  // so this unit's exposed door is reachable across runtimes. `:z` (shared
  // SELinux relabel) for the same reason renderPodmanRun emits it (prx-3urm):
  // on an SELinux-enforcing host — the common case for a production quadlet —
  // the bare mount leaves the door dir `var_run_t` and the keeper hits EACCES
  // creating its socket; `:z` relabels to `container_file_t`. Shared, not `:Z`,
  // because the fabric is shared with the kube pod; a no-op on non-SELinux hosts.
  lines.push(`Volume=${p.doorDir}:${p.doorDir}:z`);
  // The repo bind-mount + WorkingDir (mirrors renderPodmanRun; prx-u5lx). `:z`
  // for the same SELinux reason — the repo is shared by every room.
  if (p.repo) {
    lines.push(`Volume=${p.repo}:${WORK_DIR}:z`, `WorkingDir=${WORK_DIR}`);
  }
  // The wired-door env projection (a secret room that also consumes doors).
  const env = podRoomEnv(p, room.name);
  for (const key of Object.keys(env).sort()) {
    lines.push(`Environment=${key}=${env[key]!}`);
  }
  // The capability hardening floor borrowed from claude-box's door units. Egress
  // is intentionally NOT disabled (keeperd pushes); confine it to a netd door later.
  lines.push(
    "NoNewPrivileges=true",
    "DropCapability=all",
    "PidsLimit=256",
    "Memory=512m",
    "",
    "[Service]",
    "Restart=always",
    "RestartSec=5",
    "",
    "[Install]",
    "WantedBy=default.target",
  );

  return lines.join("\n") + "\n";
}

/** The default podman driver. */
export const podmanDriver: PodDriver = {
  id: "podman",
  render: renderPodmanKube,
};
