/**
 * Podman driver (prx-asr) — render a {@link PodSpec} to a Kubernetes Pod
 * manifest for `podman kube play`, mirroring the executor's Lima driver
 * (`executor/lima.ts` → `renderLima`): plain text built field-by-field for our
 * known schema (no YAML dependency, readable result), validated at the seam.
 *
 * The mapping:
 *   - each room → a container (sharing the pod's namespaces, the podman-pod
 *     property that makes the door sockets reachable across rooms);
 *   - the door fabric (`doorDir`) → one shared `emptyDir{ medium: Memory }`
 *     (tmpfs) volume mounted into every container, so the unix-socket doors live
 *     on shared memory, not a disk or the network;
 *   - each container's env → {@link podRoomEnv} for that room — the wired-door
 *     projection, i.e. `PRX_BEADS_DOOR`/`PRX_BEADS_SOCKET` for the beadsd
 *     consumer. A closed/unresolved door contributes no env (it isn't wired).
 *
 * The container *image* is the room's `RoomSpec.image` (its `-box`) when
 * declared, else a deterministic placeholder ref. The full registry ref is a
 * deploy concern (prx-zj8); everything else is real.
 */

import { PodSpecSchema, podRoomEnv, type PodSpec } from "./pod.ts";

/** A YAML double-quoted scalar — JSON string syntax is a valid YAML 1.2 scalar. */
function dq(value: string): string {
  return JSON.stringify(value);
}

/** The shared door-fabric volume name. */
const DOOR_VOLUME = "prx-doors";

/**
 * A pod driver: render a {@link PodSpec} to its native orchestration config.
 * Mirrors `ExecutorDriver` — adding a driver must not touch the room/pod specs.
 */
export interface PodDriver {
  /** Stable driver id, e.g. `podman`. */
  readonly id: string;
  /** Render the spec to the driver's native config text. */
  render(pod: PodSpec): string;
}

/**
 * Render a {@link PodSpec} to a `podman kube play` Pod manifest. Validates the
 * spec at the seam (throws on a malformed pod) so a bad input never yields
 * half-config.
 */
export function renderPodmanKube(pod: PodSpec): string {
  const p = PodSpecSchema.parse(pod);
  const lines: string[] = [
    "# Generated by prx (pod spec → podman driver, prx-asr). Do not hand-edit.",
    "apiVersion: v1",
    "kind: Pod",
    "metadata:",
    `  name: ${dq(p.name)}`,
    "spec:",
    // The door fabric: one tmpfs shared by every room's container.
    "  volumes:",
    `    - name: ${DOOR_VOLUME}`,
    "      emptyDir:",
    "        medium: Memory",
    "  containers:",
  ];

  for (const room of p.rooms) {
    lines.push(`    - name: ${dq(room.name)}`);
    // The room's `-box` image when declared; else a deterministic placeholder
    // (a room with no image yet — the full registry ref is a prx-zj8 concern).
    if (room.image) {
      lines.push(`      image: ${dq(room.image)}`);
    } else {
      lines.push(`      image: ${dq(`prx/${room.name}:latest`)} # TODO(prx-zj8): no image declared`);
    }
    lines.push("      volumeMounts:");
    lines.push(`        - name: ${DOOR_VOLUME}`);
    lines.push(`          mountPath: ${dq(p.doorDir)}`);

    const env = podRoomEnv(p, room.name);
    const keys = Object.keys(env).sort();
    if (keys.length > 0) {
      lines.push("      env:");
      for (const key of keys) {
        lines.push(`        - name: ${key}`);
        lines.push(`          value: ${dq(env[key]!)}`);
      }
    }
  }

  return lines.join("\n") + "\n";
}

/** The default podman driver. */
export const podmanDriver: PodDriver = {
  id: "podman",
  render: renderPodmanKube,
};
